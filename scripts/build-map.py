#!/usr/bin/env python3
"""
Builds apps/mobile/src/features/statewars/nigeriaPaths.ts from geoBoundaries NGA ADM1 (GRID3, CC BY 4.0).
  python3 scripts/build-map.py [path/to/geoBoundaries-NGA-ADM1_simplified.geojson]
Projects lon/lat (equirectangular, cos(lat0) scaled), simplifies with Douglas-Peucker and writes compact SVG paths.
"""
import json, math, sys, urllib.request, os

SRC = "https://github.com/wmgeolab/geoBoundaries/raw/9469f09/releaseData/gbOpen/NGA/ADM1/geoBoundaries-NGA-ADM1_simplified.geojson"
OUT = os.path.join(os.path.dirname(__file__), "..", "apps/mobile/src/features/statewars/nigeriaPaths.ts")
NAMES = {
    "Abia": "AB", "Adamawa": "AD", "Akwa Ibom": "AK", "Anambra": "AN", "Bauchi": "BA", "Bayelsa": "BY", "Benue": "BE", "Borno": "BO",
    "Cross River": "CR", "Delta": "DE", "Ebonyi": "EB", "Edo": "ED", "Ekiti": "EK", "Enugu": "EN", "Federal Capital Territory": "FC", "Abuja Federal Capital Territory": "FC",
    "Gombe": "GO", "Imo": "IM", "Jigawa": "JI", "Kaduna": "KD", "Kano": "KN", "Katsina": "KT", "Kebbi": "KE", "Kogi": "KO", "Kwara": "KW",
    "Lagos": "LA", "Nasarawa": "NA", "Niger": "NI", "Ogun": "OG", "Ondo": "ON", "Osun": "OS", "Oyo": "OY", "Plateau": "PL", "Rivers": "RI",
    "Sokoto": "SO", "Taraba": "TA", "Yobe": "YO", "Zamfara": "ZA",
}
W = 1000
EPS = 1.2  # simplification tolerance in output units

def load():
    if len(sys.argv) > 1:
        return json.load(open(sys.argv[1]))
    with urllib.request.urlopen(SRC) as r:
        return json.load(r)

def dp(pts, eps):
    if len(pts) < 3: return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    best, idx = 0, 0
    for i in range(1, len(pts) - 1):
        x0, y0 = pts[i]
        d = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1) / norm
        if d > best: best, idx = d, i
    if best > eps:
        return dp(pts[: idx + 1], eps)[:-1] + dp(pts[idx:], eps)
    return [pts[0], pts[-1]]

def main():
    gj = load()
    feats = gj["features"]
    allc = []
    def rings(geom):
        if geom["type"] == "Polygon": return [geom["coordinates"][0]]
        return [p[0] for p in geom["coordinates"]]
    for f in feats:
        for r in rings(f["geometry"]): allc += r
    minx = min(c[0] for c in allc); maxx = max(c[0] for c in allc)
    miny = min(c[1] for c in allc); maxy = max(c[1] for c in allc)
    k = math.cos(math.radians((miny + maxy) / 2))
    sx = W / ((maxx - minx) * k)
    H = round((maxy - miny) * sx)
    proj = lambda c: ((c[0] - minx) * k * sx, (maxy - c[1]) * sx)
    out = {}
    centers = {}
    for f in feats:
        name = f["properties"]["shapeName"].replace(" State", "").strip()
        code = NAMES.get(name) or NAMES.get(name.title())
        if not code:
            print("unmapped:", name); continue
        d = []
        area_best, cx, cy = 0, 0, 0
        for ring in rings(f["geometry"]):
            raw = [proj(c) for c in ring]
            # Closed ring: simplify the two halves separately (DP degenerates when start == end).
            mid = len(raw) // 2
            pts = dp(raw[: mid + 1], EPS)[:-1] + dp(raw[mid:], EPS)
            if len(pts) < 4: continue
            d.append("M" + "L".join(f"{x:.0f} {y:.0f}" for x, y in pts) + "Z")
            # polygon centroid of the largest ring, for labels
            a = sum(pts[i][0] * pts[i + 1][1] - pts[i + 1][0] * pts[i][1] for i in range(len(pts) - 1)) / 2
            if abs(a) > area_best:
                area_best = abs(a)
                cx = sum((pts[i][0] + pts[i + 1][0]) * (pts[i][0] * pts[i + 1][1] - pts[i + 1][0] * pts[i][1]) for i in range(len(pts) - 1)) / (6 * a)
                cy = sum((pts[i][1] + pts[i + 1][1]) * (pts[i][0] * pts[i + 1][1] - pts[i + 1][0] * pts[i][1]) for i in range(len(pts) - 1)) / (6 * a)
        out[code] = "".join(d)
        centers[code] = (round(cx), round(cy))
    missing = set(NAMES.values()) - set(out)
    assert not missing, f"missing states: {missing}"
    with open(OUT, "w") as fh:
        fh.write("// GENERATED by scripts/build-map.py from geoBoundaries NGA ADM1 (source: GRID3), CC BY 4.0.\n")
        fh.write("// https://www.geoboundaries.org · https://data.grid3.org — see docs/CREDITS.md\n\n")
        fh.write(f"export const MAP_WIDTH = {W};\nexport const MAP_HEIGHT = {H};\n\n")
        fh.write("export const STATE_PATHS: Record<string, string> = {\n")
        for code in sorted(out): fh.write(f'  {code}: "{out[code]}",\n')
        fh.write("};\n\nexport const STATE_CENTERS: Record<string, [number, number]> = {\n")
        for code in sorted(centers): fh.write(f"  {code}: [{centers[code][0]}, {centers[code][1]}],\n")
        fh.write("};\n")
    print(f"wrote {OUT}: {len(out)} states, {os.path.getsize(OUT)//1024} KB, {W}x{H}")

main()
