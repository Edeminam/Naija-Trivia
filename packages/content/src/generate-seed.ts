// Generates supabase/seed.sql from the shared constants and the question bank.
// Run: pnpm seed:generate   (from the repo root)
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { STATES, CATEGORIES, AVATARS, MISSION_POOL, DAILY_QUESTION_COUNT } from "@ntc/shared";
import { buildQuestions, stableUuid, mulberry32, BANKS } from "./index";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../supabase/seed.sql");

const lit = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const catId = (slug: string) => stableUuid(`category:${slug}`);
const seeded = new Set(BANKS.map((b) => b.category));

const lines: string[] = [
  "-- GENERATED by packages/content/src/generate-seed.ts — do not edit by hand.",
  "-- Idempotent: safe to re-run.",
  "begin;",
  "",
  "-- States (36 + FCT + Diaspora)",
  "insert into states (code, name, region) values",
  STATES.map((s) => `  (${lit(s.code)}, ${lit(s.name)}, ${lit(s.region)})`).join(",\n") +
    "\non conflict (code) do update set name = excluded.name, region = excluded.region;",
  "",
  "-- Categories (ones without seeded questions start inactive; seeding never deactivates one)",
  "insert into categories (id, slug, name, icon, tint, sort, active) values",
  CATEGORIES.map((c, i) => `  (${lit(catId(c.slug))}, ${lit(c.slug)}, ${lit(c.name)}, ${lit(c.icon)}, ${lit(c.tint)}, ${i}, ${seeded.has(c.slug)})`).join(",\n") +
    "\non conflict (slug) do update set name = excluded.name, icon = excluded.icon, tint = excluded.tint, sort = excluded.sort, active = categories.active or excluded.active;",
  "",
  "-- Avatars",
  "insert into avatars (id, name, skin, bg, accent, hair) values",
  AVATARS.map((a) => `  (${lit(a.id)}, ${lit(a.name)}, ${lit(a.skin)}, ${lit(a.bg)}, ${lit(a.accent)}, ${lit(a.hair)})`).join(",\n") +
    "\non conflict (id) do update set name = excluded.name, skin = excluded.skin, bg = excluded.bg, accent = excluded.accent, hair = excluded.hair;",
  "",
  "-- Missions",
  "insert into missions (slug, title, metric, target, reward) values",
  MISSION_POOL.map((m) => `  (${lit(m.slug)}, ${lit(m.title)}, ${lit(m.metric)}, ${m.target}, ${m.reward})`).join(",\n") +
    "\non conflict (slug) do update set title = excluded.title, metric = excluded.metric, target = excluded.target, reward = excluded.reward;",
  "",
  "-- Season 1 starts Monday 28 Sep 2026, 00:00 WAT (28-day seasons)",
  "insert into seasons (number, starts_at, ends_at) values (1, '2026-09-27T23:00:00Z', '2026-10-25T23:00:00Z') on conflict (number) do nothing;",
  "",
];

const questions = buildQuestions();
lines.push(`-- Questions (${questions.length})`);
for (let i = 0; i < questions.length; i += 100) {
  const chunk = questions.slice(i, i + 100);
  lines.push(
    "insert into questions (id, category_id, text, options, correct_index, difficulty, fact, source_url, status) values",
    chunk
      .map(
        (q) =>
          `  (${lit(q.id)}, ${lit(catId(q.category))}, ${lit(q.text)}, ${lit(JSON.stringify(q.options))}::jsonb, ${q.correctIndex}, ${q.difficulty}, ${lit(q.fact)}, ${lit(q.sourceUrl)}, '${q.status}')`,
      )
      .join(",\n") +
      "\non conflict (id) do update set text = excluded.text, options = excluded.options, correct_index = excluded.correct_index, difficulty = excluded.difficulty, fact = excluded.fact, source_url = excluded.source_url,\n" +
      "  status = case when questions.status = 'in_review' and excluded.status = 'live' then 'live' else questions.status end;",
    "",
  );
}

// Three Daily Naija sets: a balanced mix of live questions, easy → hard.
const live = questions.filter((q) => q.status === "live");
const rand = mulberry32(20261006);
const used = new Set<string>();
const dates = ["2026-10-06", "2026-10-07", "2026-10-08"];
lines.push("-- Daily Naija sets");
for (const date of dates) {
  const picks: string[] = [];
  const diffs = [1, 1, 2, 2, 3, 3, 3, 4, 4, 5];
  const cats = [...seeded];
  for (let k = 0; k < DAILY_QUESTION_COUNT; k++) {
    const cat = cats[k % cats.length];
    const d = diffs[k]!;
    const pool = live.filter((q) => q.category === cat && q.difficulty === d && !used.has(q.id));
    const fallback = live.filter((q) => q.difficulty === d && !used.has(q.id));
    const list = pool.length ? pool : fallback;
    const pick = list[Math.floor(rand() * list.length)]!;
    used.add(pick.id);
    picks.push(pick.id);
  }
  lines.push(`insert into daily_sets (daily_date, question_ids) values ('${date}', array[${picks.map(lit).join(", ")}]::uuid[]) on conflict (daily_date) do nothing;`);
}

lines.push("", "commit;", "");
writeFileSync(out, lines.join("\n"));
const counts = Object.fromEntries(BANKS.map((b) => [b.category, b.questions.length]));
const review = questions.filter((q) => q.status === "in_review").length;
console.log(`Wrote ${out}\n  questions: ${questions.length} (${questions.length - review} live, ${review} in_review)`, counts);
